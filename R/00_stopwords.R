load_stopwords <- function(path = "data/swl.txt") {
  if (!file.exists(path)) stop("Stop-word file not found: ", path)

  stop_words_ru <- readLines(path, encoding = "UTF-8")
  stop_words_ru <- trimws(stop_words_ru)
  stop_words_ru <- stop_words_ru[stop_words_ru != ""]

  stop_words_extra <- c(
    "блять", "сука", "пиздец", "хуй", "хуйня", "нахуй", "ебать", "ебаный",
    "ебанутый", "ахуеть", "пизда", "заебал", "заебали", "заебись",
    "бля", "херня", "похуй", "говно", "мудак", "уебок", "пидор",
    "https", "http", "www", "youtube", "instagram", "facebook", "twitter",
    "telegram", "t.me", "vk", "youtu.be", "rutube", "dzen",
    "крч", "кароч", "короче", "типа", "тупо", "чисто", "ваще", "воще",
    "наверное", "наверно", "конечно", "кстати", "блин", "вау", "ого",
    "ага", "ладно", "вообще", "какбы", "как-бы", "вроде",
    "лол", "кек", "че", "чо", "чё", "ща", "сейчас", "пж", "спс",
    "спасибо", "окей", "ок", "норм", "нормально", "бро", "братан",
    "чувак", "чуваки", "пацаны", "ребята", "народ", "плиз", "пожалуйста",
    "сегодня", "вчера", "завтра", "утром", "вечером", "ночью", "днём",
    "й", "ё", "ъ", "ь", "ы", "э", "ю", "я"
  )

  unique(c(stop_words_ru, stop_words_extra))
}
